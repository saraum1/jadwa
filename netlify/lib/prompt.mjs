export function buildSystemPrompt(mode, facts, previousMeeting) {
  const role = ROLES[mode] || ROLES.chat;
  const prev = previousMeeting ? `\n\n## الاجتماع السابق\n${JSON.stringify(previousMeeting)}` : '';
  return `${CORE}\n\n${role}\n\n## نتائج التحليل (المصدر الوحيد للأرقام)\n${JSON.stringify(facts)}${prev}`;
}

export const MODES = Object.keys(ROLES);
